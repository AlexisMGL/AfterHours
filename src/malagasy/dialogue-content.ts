// Original scenes recombine the already sourced expressions in content.ts.
// Translation is learner-controlled; Malagasy is always the first visible text.
const turn = (speaker: CharacterId, text: string, translation: string, highlight?: string): DialogueTurn => ({ speaker, text, translation, highlight });
const lova = (text: string, translation: string, highlight?: string): DialogueTurn => turn('lova', text, translation, highlight);
const mia = (text: string, translation: string, highlight?: string): DialogueTurn => turn('mia', text, translation, highlight);
const scene = (id: string, setting: string, turns: DialogueTurn[], malagasy: string, french: string): DialogueScene => ({ id, setting, turns, takeaway: { malagasy, french } });

